// Roundtrip: decrypt(encrypt(x, k), k) = x (FIPS-197 C.1 key/block).
#[test]
fn test_aes_roundtrip() {
    let key = [0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f];
    let pt = [0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff];
    let ct = bitvec_aes::aes_encrypt(&pt, &key);
    let back = bitvec_aes::aes_decrypt(&ct, &key);
    let mut i = 0usize;
    while i < 16 {
        assert_eq!(back[i], pt[i]);
        i = i + 1;
    }
}

