// ── permutation ─────────────────────────────────────────────────────────────

/// Bit-permutation: map each output bit `i` (0..n-1) to input bit `table[i]`.
/// `table` stores u64 bit positions; `input` is right-aligned (bits 0..w-1).
pub fn permute(input: u64, table: &[u8], n: u32) -> u64 {
    let mut out = 0u64;
    let mut i = 0u32;
    while i < n {
        let src = table[i as usize] as u32;
        let bit = (input >> src) & 1u64;
        out = out | (bit << (n - 1u32 - i));
        i = i + 1u32;
    }
    out
}

// ── key schedule ────────────────────────────────────────────────────────────

/// 28-bit left rotation (masked to 28 bits).
pub fn rotate_left_28(x: u32, n: u32) -> u32 {
    let mask = 0x0FFFFFFFu32;
    let r = (x << n) | (x >> (28u32 - n));
    r & mask
}

/// DES key schedule: 64-bit key → 16 round keys (48 bits each).
pub fn key_schedule(key: u64) -> [u64; 16] {
    let pc1 = permute(key, &PC1, 56u32);
    let mut c = (pc1 >> 28u32) as u32 & 0x0FFFFFFF;
    let mut d = pc1 as u32 & 0x0FFFFFFF;
    let mut rk = [0u64; 16];
    let mut r = 0u32;
    while r < 16u32 {
        let s = SHIFTS[r as usize] as u32;
        c = rotate_left_28(c, s);
        d = rotate_left_28(d, s);
        let cd = (c as u64) << 28u32 | (d as u64);
        rk[r as usize] = permute(cd, &PC2, 48u32);
        r = r + 1u32;
    }
    rk
}

// ── Feistel round function ──────────────────────────────────────────────────

/// The DES Feistel function `f(R, K)`: expand R (32b), xor with K (48b),
/// substitute through 8 S-boxes, and permute back to 32 bits.
pub fn feistel(r: u64, round_key: u64) -> u64 {
    let expanded = permute(r, &E, 48u32);
    let x = expanded ^ round_key;
    let mut out = 0u64;
    let mut i = 0u32;
    while i < 8u32 {
        let shift = (7u32 - i) * 6u32;
        let six = (x >> shift) & 0x3Fu64;
        let row = ((six >> 4) & 2u64) | (six & 1u64);
        let col = (six >> 1) & 0xFu64;
        let val = SBOXES[i as usize][(row * 16u64 + col) as usize];
        out = (out << 4u32) | (val as u64);
        i = i + 1u32;
    }
    permute(out, &P, 32u32)
}

// ── encrypt / decrypt ───────────────────────────────────────────────────────

/// DES single-block encryption.
pub fn des_encrypt(block: u64, key: u64) -> u64 {
    let ip = permute(block, &IP, 64u32);
    let rk = key_schedule(key);
    let mut l = (ip >> 32u32) & 0xFFFFFFFFu64;
    let mut r = ip & 0xFFFFFFFFu64;
    let mut round = 0u32;
    while round < 16u32 {
        let f = feistel(r, rk[round as usize]);
        let new_r = l ^ f;
        l = r;
        r = new_r;
        round = round + 1u32;
    }
    let pre = (r << 32u32) | l;
    permute(pre, &FP, 64u32)
}

/// DES single-block decryption (round keys in reverse order).
pub fn des_decrypt(block: u64, key: u64) -> u64 {
    let ip = permute(block, &IP, 64u32);
    let rk = key_schedule(key);
    let mut l = (ip >> 32u32) & 0xFFFFFFFFu64;
    let mut r = ip & 0xFFFFFFFFu64;
    let mut round = 0u32;
    while round < 16u32 {
        let f = feistel(r, rk[(15u32 - round) as usize]);
        let new_r = l ^ f;
        l = r;
        r = new_r;
        round = round + 1u32;
    }
    let pre = (r << 32u32) | l;
    permute(pre, &FP, 64u32)
}